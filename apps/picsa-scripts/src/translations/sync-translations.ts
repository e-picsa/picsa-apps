/**
 * Translations Sync
 *
 * Pulls app translations from Supabase and writes per-locale JSON files consumed
 * via libs/i18n/assets. Output mirrors the dashboard translations "Export All"
 * action, so the manual zip download/copy step is no longer required.
 *
 * Usage:
 *   yarn scripts:translations:sync [--country=mw] [--locale=mw_ny] [--local] [--audit-only]
 *
 * Args:
 *   --country=<code>    Only pull rows for one country (plus global/unscoped rows).
 *                       Default pulls every row so all country locales stay complete.
 *   --locale=<code>     Only write a single locale file (e.g. mw_ny)
 *   --local             Pull from the local Supabase container instead of remote.
 *                       Default pulls remote via apps/picsa-server/.env.server
 *   --env=<path>        Load environment variables from a custom env file
 *   --audit-only        Report file changes without writing (alias: --dry-run)
 *   --include-archived  Include archived rows. Archived rows are excluded by
 *                       default as they are no longer referenced by the app.
 */
import * as fs from 'fs';
import * as path from 'path';
import { LOCALES_DATA_HASHMAP } from '@picsa/data/deployments';
import type { Database } from '@picsa/server-types';
import type { SupabaseClient } from '@supabase/supabase-js';

import { getSyncSupabaseClient } from '../climate/sync-climate-data';

type ITranslationRow = Database['public']['Tables']['translations']['Row'];

const ROOT_DIR = path.resolve(__dirname, '../../../../');
const TRANSLATIONS_DIR = path.join(ROOT_DIR, 'libs/i18n/assets');
const SUPPORTED_COUNTRIES = ['mw', 'zm', 'zw', 'tj'];

interface CliArgs {
  country?: string;
  locale?: string;
  env?: string;
  local?: boolean;
  auditOnly?: boolean;
  includeArchived?: boolean;
}

interface ILocaleSyncSummary {
  locale: string;
  status: 'NEW' | 'UPDATED' | 'UNCHANGED' | 'SKIPPED';
  added: number;
  removed: number;
  changed: number;
}

const FLAG_HANDLERS: Record<string, (result: CliArgs) => void> = {
  '--local': (result) => {
    result.local = true;
  },
  '--audit-only': (result) => {
    result.auditOnly = true;
  },
  '--dry-run': (result) => {
    result.auditOnly = true;
  },
  '--include-archived': (result) => {
    result.includeArchived = true;
  },
};

const VALUED_OPTIONS: Record<string, (result: CliArgs, value: string) => void> = {
  '--country': (result, value) => {
    result.country = value.toLowerCase();
  },
  '--locale': (result, value) => {
    result.locale = value;
  },
  '--env': (result, value) => {
    result.env = value;
  },
};

function parseCliArgs(argv = process.argv.slice(2)): CliArgs {
  const result: CliArgs = {};

  for (let i = 0; i < argv.length; i++) {
    const [flag, inlineValue] = argv[i].split('=');

    const flagHandler = FLAG_HANDLERS[flag];
    if (flagHandler) {
      flagHandler(result);
      continue;
    }

    const optionHandler = VALUED_OPTIONS[flag];
    if (!optionHandler) {
      continue;
    }

    const value = inlineValue ?? argv[++i];
    if (!value) {
      throw new Error(`Missing value for ${flag}`);
    }
    optionHandler(result, value);
  }

  return result;
}

/** Composite id generated by combination of row metadata, country code and en text (mirrors dashboard service) */
function generateTranslationId(row: ITranslationRow): string {
  const { tool, context, text, country_code } = row;
  const parts = country_code && country_code !== 'global' ? [country_code, tool, context, text] : [tool, context, text];
  return parts.map((part) => part?.toLowerCase().replace(/[^a-z0-9]/g, '')).join('-');
}

/** Locale columns are typed as string | null, metadata columns are not translation values */
function getTranslationValue(row: ITranslationRow, locale: string): string | null {
  const value = (row as unknown as Record<string, unknown>)[locale];
  return typeof value === 'string' ? value : null;
}

/**
 * Build locale lookup, preferring human text keys and retaining legacy row ids.
 * Untranslated strings are wrapped in bullets so missing translations stay visible in-app.
 */
function buildLocaleTranslations(rows: ITranslationRow[], locale: string): Record<string, string> {
  const translations = new Map<string, string>();
  // Stable text ordering keeps output diffable between runs (mirrors dashboard export)
  const sortedRows = [...rows].sort((a, b) => (a.text.toLowerCase() > b.text.toLowerCase() ? 1 : -1));

  for (const row of sortedRows) {
    const translatedText = getTranslationValue(row, locale);
    const generatedId = generateTranslationId(row);
    const shouldIncludeId = Boolean(row.id) && row.id !== generatedId;

    if (translatedText) {
      translations.set(row.text, translatedText);
      if (shouldIncludeId) {
        translations.set(row.id, translatedText);
      }
      continue;
    }

    if (!translations.has(row.text)) {
      translations.set(row.text, `•${row.text}•`);
    }
    if (shouldIncludeId && !translations.has(row.id)) {
      translations.set(row.id, `•${row.id}•`);
    }
  }

  return Object.fromEntries(translations);
}

function readExistingTranslations(localePath: string): Record<string, string> {
  if (!fs.existsSync(localePath)) {
    return {};
  }
  try {
    return JSON.parse(fs.readFileSync(localePath, 'utf-8'));
  } catch {
    return {};
  }
}

function diffTranslations(previous: Record<string, string>, next: Record<string, string>) {
  const previousKeys = Object.keys(previous);
  const nextKeys = Object.keys(next);
  return {
    added: nextKeys.filter((key) => !(key in previous)).length,
    removed: previousKeys.filter((key) => !(key in next)).length,
    changed: nextKeys.filter((key) => key in previous && previous[key] !== next[key]).length,
  };
}

/** Resolve if the table actually stores a locale column (all English locales resolve to global_en) */
function hasLocaleColumn(rows: ITranslationRow[], locale: string): boolean {
  if (locale.endsWith('_en')) {
    return false;
  }
  return rows.some((row) => locale in row);
}

async function fetchTranslations(
  client: SupabaseClient,
  options: { country?: string; includeArchived?: boolean },
): Promise<ITranslationRow[]> {
  let query = client.from('translations').select('*');

  if (options.country) {
    query = query.or(`country_code.eq.${options.country},country_code.is.null,country_code.eq.global`);
  }

  if (!options.includeArchived) {
    query = query.not('archived', 'is', true);
  }

  const { data, error } = await query.order('text', { ascending: true }).order('id', { ascending: true });

  if (error) {
    throw new Error(`translations pull failed: ${error.message}`);
  }

  return (data ?? []) as ITranslationRow[];
}

function writeLocaleFile(
  locale: string,
  rows: ITranslationRow[],
  options: { auditOnly?: boolean },
): ILocaleSyncSummary {
  const localePath = path.join(TRANSLATIONS_DIR, `${locale}.json`);
  const previous = readExistingTranslations(localePath);

  // Missing columns are written as empty files (app falls back to key text for English)
  if (!hasLocaleColumn(rows, locale)) {
    if (Object.keys(previous).length > 0) {
      console.warn(`  [${locale}] ⚠️  no '${locale}' column in translations table - keeping existing file unchanged`);
      return { locale, status: 'SKIPPED', added: 0, removed: 0, changed: 0 };
    }
    if (!options.auditOnly) {
      fs.writeFileSync(localePath, '{}', 'utf-8');
    }
    return { locale, status: 'UNCHANGED', added: 0, removed: 0, changed: 0 };
  }

  const next = buildLocaleTranslations(rows, locale);
  const { added, removed, changed } = diffTranslations(previous, next);
  const isUnchanged = added === 0 && removed === 0 && changed === 0;

  if (isUnchanged) {
    return { locale, status: 'UNCHANGED', added, removed, changed };
  }

  if (!options.auditOnly) {
    if (!fs.existsSync(TRANSLATIONS_DIR)) {
      fs.mkdirSync(TRANSLATIONS_DIR, { recursive: true });
    }
    // No trailing newline to match dashboard export output
    fs.writeFileSync(localePath, JSON.stringify(next, null, 2), 'utf-8');
  }

  const status = Object.keys(previous).length === 0 ? 'NEW' : 'UPDATED';
  return { locale, status, added, removed, changed };
}

async function main(): Promise<void> {
  const args = parseCliArgs();

  if (args.country && !SUPPORTED_COUNTRIES.includes(args.country)) {
    throw new Error(`Unsupported country: ${args.country} (expected one of ${SUPPORTED_COUNTRIES.join(', ')})`);
  }

  const locales = Object.keys(LOCALES_DATA_HASHMAP);
  if (args.locale && !locales.includes(args.locale)) {
    throw new Error(`Unknown locale: ${args.locale} (expected one of ${locales.join(', ')})`);
  }

  const targetLocales = args.locale ? [args.locale] : locales;
  const client = getSyncSupabaseClient({ local: args.local, env: args.env });

  console.log(`\nSyncing translations (${args.local ? 'LOCAL' : 'REMOTE'})${args.country ? ` [${args.country}]` : ''}`);
  const rows = await fetchTranslations(client, {
    country: args.country,
    includeArchived: args.includeArchived,
  });
  console.log(`  Fetched ${rows.length} translation row(s)`);

  // Never wipe local assets from an empty/unexpected query result
  if (rows.length === 0) {
    throw new Error('No translation rows returned - refusing to write empty locale files');
  }

  const summaries = targetLocales.map((locale) => writeLocaleFile(locale, rows, { auditOnly: args.auditOnly }));

  const written = summaries.filter((summary) => summary.status === 'NEW' || summary.status === 'UPDATED');
  for (const summary of written) {
    const { locale, status, added, removed, changed } = summary;
    console.log(`  [${locale}] ${status}: +${added} -${removed} ~${changed}${args.auditOnly ? ' (audit only)' : ''}`);
  }

  console.log('\n======================================================');
  console.log('[Translations Sync Complete]');
  console.log(`  Locales Checked: ${summaries.length}`);
  console.log(`  Locales Changed: ${written.length}`);
  console.log(`  Locales Skipped: ${summaries.filter((summary) => summary.status === 'SKIPPED').length}`);
  console.log('======================================================\n');

  if (written.length === 0) {
    console.log('✅ Translation assets already up to date');
  } else if (args.auditOnly) {
    console.log('ℹ️  Audit only - no files written');
  } else {
    console.log('✅ Translation assets synced');
  }
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
